#!/usr/bin/env python3
"""Converts TrueType fonts to Adafruit GFX bitmap fonts (ASCII 0x20-0x7E) for
the Tab5's native-resolution UI, written to src/core/fonts_wide.h.

    tools/make_font.py

The fonts and sizes are listed in FONTS below. Needs Pillow and the DejaVu
fonts (Debian: fonts-dejavu-core). DejaVu is under the Bitstream Vera licence,
which allows embedding.
"""
import os
from PIL import Image, ImageDraw, ImageFont

DEJAVU = '/usr/share/fonts/truetype/dejavu/'
# name, file, pixel size
FONTS = [
    ('WideMono', DEJAVU + 'DejaVuSansMono.ttf', 26),
    ('WideMonoBold', DEJAVU + 'DejaVuSansMono-Bold.ttf', 26),
    ('WideSmall', DEJAVU + 'DejaVuSansMono.ttf', 21),
]
OUT = os.path.join(os.path.dirname(__file__), '..', 'src', 'core', 'fonts_wide.h')


def convert(name, path, size):
    font = ImageFont.truetype(path, size)
    ascent, descent = font.getmetrics()
    bits, glyphs = [], []
    for code in range(0x20, 0x7F):
        ch = chr(code)
        adv = round(font.getlength(ch))
        box = font.getbbox(ch)   # relative to the top of the ascent
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        offset = len(bits) // 8
        if w and h:
            img = Image.new('1', (w, h), 0)
            d = ImageDraw.Draw(img)
            d.fontmode = '1'   # no anti-aliasing: GFX fonts are 1 bit
            d.text((-box[0], -box[1]), ch, font=font, fill=1)
            for y in range(h):
                for x in range(w):
                    bits.append(1 if img.getpixel((x, y)) else 0)
        while len(bits) % 8:
            bits.append(0)
        # yOffset is from the baseline (GFX) to the top of the bitmap
        glyphs.append((offset, w, h, adv, box[0], box[1] - ascent))
    data = bytes(int(''.join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8))
    out = [f'// {os.path.basename(path)} at {size} px, made by tools/make_font.py',
           f'static const uint8_t {name}Bitmaps[] = {{']
    for i in range(0, len(data), 16):
        out.append('  ' + ', '.join(f'0x{b:02X}' for b in data[i:i + 16]) + ',')
    out.append('};')
    out.append(f'static const lgfx::GFXglyph {name}Glyphs[] = {{')
    for code, g in zip(range(0x20, 0x7F), glyphs):
        out.append('  {%d, %d, %d, %d, %d, %d},  // %r' % (g + (chr(code),)))
    out.append('};')
    out.append(f'static const lgfx::GFXfont {name}((uint8_t*){name}Bitmaps, (lgfx::GFXglyph*){name}Glyphs, '
               f'0x20, 0x7E, {ascent + descent});')
    return '\n'.join(out)


def main():
    parts = ['#pragma once', '// Fonts for the native-resolution (Tab5) UI. Generated by tools/make_font.py.',
             '#include <M5GFX.h>', '', 'namespace ui {', '']
    for f in FONTS:
        parts.append(convert(*f))
        parts.append('')
    parts.append('}  // namespace ui')
    open(OUT, 'w').write('\n'.join(parts) + '\n')
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
