"""Gzips web/index.html into src/core/web_page.h (the page the web server sends).

Runs before every PlatformIO build (extra_scripts in platformio.ini) and can be
run by hand: python tools/web_embed.py
"""
import gzip
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__))) if "__file__" in globals() else os.getcwd()
SRC = os.path.join(ROOT, "web", "index.html")
OUT = os.path.join(ROOT, "src", "core", "web_page.h")


def build():
    with open(SRC, "rb") as f:
        data = gzip.compress(f.read(), compresslevel=9, mtime=0)
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 20]) for i in range(0, len(data), 20)]
    text = (
        "// Generated by tools/web_embed.py from web/index.html - edit that instead.\n"
        "#pragma once\n#include <stddef.h>\n#include <stdint.h>\n\n"
        f"static const size_t WEB_PAGE_GZ_LEN = {len(data)};\n"
        "static const uint8_t WEB_PAGE_GZ[] = {\n    " + ",\n    ".join(rows) + "\n};\n"
    )
    old = open(OUT).read() if os.path.exists(OUT) else ""
    if old != text:
        with open(OUT, "w") as f:
            f.write(text)
        print(f"web_embed: {os.path.getsize(SRC)} bytes -> {len(data)} gzipped")


if "Import" in globals():   # running inside PlatformIO (SCons)
    Import("env")  # noqa: F821
    ROOT = env.subst("$PROJECT_DIR")  # noqa: F821
    SRC = os.path.join(ROOT, "web", "index.html")
    OUT = os.path.join(ROOT, "src", "core", "web_page.h")
build()
